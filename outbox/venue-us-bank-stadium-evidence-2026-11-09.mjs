const strip = l => l.replace(/^verify\t[^\t]*\t﻿?\d{4}-\d\d-\d\dT[\d:.]+Z /, '').replace(/^live\t[^\t]*\t﻿?\d{4}-\d\d-\d\dT[\d:.]+Z /, '')
const failLines = file => readFileSync(join(sp, file), 'utf8').split('\n')
  .map(strip)
  .filter((l, i, a) => /^FAIL /.test(l) || (i > 0 && /^FAIL /.test(a[i - 1]) && /^\s+→/.test(l)))
