// File a self-closing bug ticket ON field-relay-nba when its soccer briefs still
// carry the CC-CMD-2026-08-22 defects — automated, cross-repo, no PR.
//
// WHY THIS RUNNER EXISTS
//
// `cc-cmd-followup.mjs` reports `still gen` into THIS repo's logs, where only we
// see it. The relay maintainer never gets a ticket. This runner closes that gap:
// it reads live EPL briefs over the relay's HTTP API, scans them with the shared
// defect scanner, and — through the GitHub API — files or updates an issue on
// field-relay-nba carrying the VERBATIM offending briefs and the enumerated
// failing rows, then closes that issue itself on the first run where every EPL
// brief is clean. Same file-and-close pattern the drift-sentinel already uses for
// its own repo, aimed cross-repo.
//
// It cannot write the relay's CODE (this session cannot read that repo, and a
// blind fix committed to their main is exactly what the confidence bar forbids).
// It writes the ONE thing it can author correctly without their source: an
// actionable, evidence-carrying, self-closing bug report.
//
// CONFIG (env)
//   GH_TOKEN   a token with issues:write on TARGET. Absent → the runner SKIPS
//              (warns, exit 0), so it is safe to wire into drift-sentinel before
//              the secret exists. This is not a fallback hiding a bug; the
//              cross-repo reporter is simply not configured yet.
//   TARGET     owner/repo to file against. Default: the relay.
//   RELAY      relay base URL. Default: the production relay.
//   RUN_URL    optional link back to the runner, embedded in the issue.
//
// MODES
//   (default)   scan live briefs, then create/update/close the issue.
//   --dry-run   scan and print the intended action; no issue write.
//   --self-test the pure logic (scan, decideIssueAction, issueBody), no network.
//
// Node 22+ (global fetch). Self-test aside, no dependencies beyond node: builtins
// and the shared scanner.

import { soccerBriefDefect } from './soccer-brief-defect.mjs'
import { isMain } from './checks.mjs'

const TARGET = process.env.TARGET || 'jeffunglesbee-create/field-relay-nba'
const RELAY = process.env.RELAY || 'https://field-relay-nba.jeffunglesbee.workers.dev'
const PROBE = '/archive/query?sport=EPL&limit=40'
const ISSUE_TITLE = 'Soccer briefs carry cross-sport vocabulary / a wrong season-stat model'

// Gated on isMain so importing this module for its exported helpers (scanBriefs,
// decideIssueAction, issueBody) never runs the self-test or the live path and
// never exits the caller — the property import-purity-check enforces.
const DRY_RUN = process.argv.includes('--dry-run')
const SELF_TEST = isMain(import.meta.url) && process.argv.includes('--self-test')

const FOOTER = '\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_'

/// Scan a batch of brief rows into offenders + observability.
export const scanBriefs = rows => {
  const withText = (Array.isArray(rows) ? rows : []).filter(r => (r?.brief_text || '').trim() !== '')
  const offenders = withText
    .map(r => ({ id: r.id || r.game_id || '(no id)', defect: soccerBriefDefect(r.brief_text), text: r.brief_text }))
    .filter(o => o.defect !== null)
  return { rowsPresent: withText.length > 0, count: withText.length, offenders }
}

/// The one decision, isolated for testing. `null` open issue means none exists.
///   no rows        → skip   (cannot conclude; leave the issue untouched)
///   offenders      → update if an issue is open, else create
///   clean + rows   → close if an issue is open, else noop
export const decideIssueAction = ({ rowsPresent, offenders, openIssueNumber }) => {
  if (!rowsPresent) return 'skip'
  if (offenders.length > 0) return openIssueNumber ? 'update' : 'create'
  return openIssueNumber ? 'close' : 'noop'
}

const trunc = (s, n = 300) => (s.length > n ? s.slice(0, n) + '…' : s)

/// The issue/comment body. Pure, so the evidence format is testable.
export const issueBody = (offenders, runUrl) => {
  const lines = [
    `The relay is still generating EPL briefs that carry the defects in`,
    `\`CC-CMD-2026-08-22-brief-sport-contamination\`. Enumerated failing rows this run:`,
    '',
  ]
  offenders.forEach((o, i) => {
    lines.push(`${i + 1}. **${o.id}** — ${o.defect}`)
    lines.push(`   > ${trunc(o.text).replace(/\n+/g, ' ')}`)
  })
  lines.push('')
  lines.push('The desk catches these on the card; the ask is that the relay stop generating them —')
  lines.push('ground soccer briefs in soccer stats and the league table, not a W-D-L record.')
  lines.push('For EPL the table is reachable via the already-proxied `/fpl/bootstrap-static`.')
  lines.push('')
  lines.push('This ticket closes itself on the first run where every returned EPL brief is clean.')
  if (runUrl) lines.push(`\n_Filed by field-laboratory relay-brief-watch. Run: ${runUrl}_`)
  return lines.join('\n') + FOOTER
}

// ── self-test: pure logic, no network ────────────────────────────────────────

if (SELF_TEST) {
  const { createChecks } = await import('./checks.mjs')
  const { check, summarize } = createChecks()

  const EVERTON = { id: 'epl_1', brief_text: 'Everton maintains a 107.7 DRTG, best in the NBA, despite playing soccer tonight.' }
  const BRENTFORD = { id: 'epl_2', brief_text: 'Brentford leads Spurs 3-0. Both teams hold 0-0-0 records. The game remains a 0-0-0 stalemate.' }
  const CLEAN = { id: 'epl_3', brief_text: 'Arsenal beat Coventry 3-0; Saka scored in the 34th. Arsenal sit top on goal difference.' }

  const dirty = scanBriefs([EVERTON, BRENTFORD, CLEAN])
  check('scanBriefs finds exactly the two offenders and leaves the clean one',
    dirty.offenders.length === 2 && dirty.rowsPresent === true &&
    dirty.offenders.map(o => o.id).join(',') === 'epl_1,epl_2',
    `offenders: ${dirty.offenders.map(o => o.id).join(',')}`)

  const clean = scanBriefs([CLEAN])
  check('a clean batch has no offenders but is observable',
    clean.offenders.length === 0 && clean.rowsPresent === true, 'clean batch misread')

  const empty = scanBriefs([])
  check('an empty batch is not observable (rowsPresent false)',
    empty.rowsPresent === false, 'empty batch read as observable')

  check('decideIssueAction: no rows → skip (never touch the issue on no data)',
    decideIssueAction({ rowsPresent: false, offenders: [], openIssueNumber: null }) === 'skip', 'no-rows acted')
  check('decideIssueAction: offenders + no open issue → create',
    decideIssueAction({ rowsPresent: true, offenders: [1], openIssueNumber: null }) === 'create', 'not created')
  check('decideIssueAction: offenders + open issue → update',
    decideIssueAction({ rowsPresent: true, offenders: [1], openIssueNumber: 7 }) === 'update', 'not updated')
  check('decideIssueAction: clean + open issue → close (self-closing)',
    decideIssueAction({ rowsPresent: true, offenders: [], openIssueNumber: 7 }) === 'close', 'not closed')
  check('decideIssueAction: clean + no issue → noop (nothing to do)',
    decideIssueAction({ rowsPresent: true, offenders: [], openIssueNumber: null }) === 'noop', 'not noop')

  const body = issueBody(dirty.offenders, 'https://run')
  check('issueBody enumerates each offender with its verbatim text and carries the footer',
    body.includes('epl_1') && body.includes('epl_2') && body.includes('DRTG') &&
    body.includes('Generated by [Claude Code]'),
    'evidence or footer missing from the issue body')
  check('issueBody truncates a very long brief rather than dumping it whole',
    issueBody([{ id: 'x', defect: 'd', text: 'y'.repeat(500) }], '').includes('…'),
    'a 500-char brief is not truncated')

  process.exit(summarize() === 0 ? 0 : 1)
}

// ── live: read briefs, then create/update/close the issue ────────────────────
//
// Guarded by isMain so importing this module (for its exported helpers) never
// touches the network or exits the caller. Body kept at its own indentation
// rather than re-flowed 75 lines for a brace.
if (isMain(import.meta.url)) {

const TOKEN = process.env.GH_TOKEN
if (!TOKEN) {
  console.log('::warning::GH_TOKEN not set — relay-brief-watch skipped (the cross-repo reporter is not configured; add SIBLING_REPO_TOKEN with issues:write on the relay).')
  process.exit(0)
}

const api = async (path, init = {}) => fetch(`https://api.github.com${path}`, {
  ...init,
  signal: AbortSignal.timeout(30000),
  headers: {
    Authorization: `Bearer ${TOKEN}`,
    Accept: 'application/vnd.github+json',
    'X-GitHub-Api-Version': '2022-11-28',
    'User-Agent': 'field-laboratory-relay-brief-watch',
    ...(init.body ? { 'Content-Type': 'application/json' } : {}),
  },
})

// Read the live briefs. An unreachable relay is not this repo's drift, so it is
// a skip, not a failure — the same posture cc-cmd-followup takes.
let rows
try {
  const r = await fetch(`${RELAY}${PROBE}`, { signal: AbortSignal.timeout(20000) })
  if (!r.ok) { console.log(`::warning::relay probe HTTP ${r.status} — skipped this run`); process.exit(0) }
  rows = (await r.json())?.results
} catch (e) {
  console.log(`::warning::relay unreachable (${String(e).slice(0, 60)}) — skipped this run`)
  process.exit(0)
}

const { rowsPresent, count, offenders } = scanBriefs(rows)
console.log(`scanned ${count} EPL brief(s); ${offenders.length} carrying a defect`)

// Find an existing open ticket by exact title.
const q = encodeURIComponent(`repo:${TARGET} is:issue is:open in:title "${ISSUE_TITLE}"`)
const search = await api(`/search/issues?q=${q}`)
let openIssueNumber = null
if (search.ok) {
  const hit = (await search.json()).items?.find(i => i.title === ISSUE_TITLE)
  openIssueNumber = hit?.number ?? null
} else {
  console.log(`::warning::issue search HTTP ${search.status} — proceeding as if no open issue`)
}

const action = decideIssueAction({ rowsPresent, offenders, openIssueNumber })
const runUrl = process.env.RUN_URL || ''

if (DRY_RUN) {
  console.log(`[dry-run] action: ${action}${openIssueNumber ? ` (open issue #${openIssueNumber})` : ''}`)
  if (offenders.length) console.log(issueBody(offenders, runUrl))
  process.exit(0)
}

const fail = (msg) => { console.log(`::error::${msg}`); process.exit(1) }

if (action === 'skip') { console.log('no EPL briefs returned — nothing to conclude, issue left as-is'); process.exit(0) }
if (action === 'noop') { console.log('EPL briefs clean and no open issue — nothing to do'); process.exit(0) }

if (action === 'create') {
  const r = await api(`/repos/${TARGET}/issues`, {
    method: 'POST',
    body: JSON.stringify({ title: ISSUE_TITLE, body: issueBody(offenders, runUrl) }),
  })
  if (!r.ok) fail(`issue create HTTP ${r.status} ${(await r.text()).slice(0, 160)}`)
  console.log(`filed issue: ${(await r.json()).html_url}`)
} else if (action === 'update') {
  const r = await api(`/repos/${TARGET}/issues/${openIssueNumber}/comments`, {
    method: 'POST',
    body: JSON.stringify({ body: issueBody(offenders, runUrl) }),
  })
  if (!r.ok) fail(`issue comment HTTP ${r.status} ${(await r.text()).slice(0, 160)}`)
  console.log(`updated issue #${openIssueNumber}: ${(await r.json()).html_url}`)
} else if (action === 'close') {
  const c = await api(`/repos/${TARGET}/issues/${openIssueNumber}/comments`, {
    method: 'POST',
    body: JSON.stringify({ body: `Every EPL brief returned this run is clean of the flagged defects. Closing automatically; reopened if a later run sees the defect again.${FOOTER}` }),
  })
  if (!c.ok) fail(`close comment HTTP ${c.status} ${(await c.text()).slice(0, 160)}`)
  const r = await api(`/repos/${TARGET}/issues/${openIssueNumber}`, {
    method: 'PATCH',
    body: JSON.stringify({ state: 'closed', state_reason: 'completed' }),
  })
  if (!r.ok) fail(`issue close HTTP ${r.status} ${(await r.text()).slice(0, 160)}`)
  console.log(`closed issue #${openIssueNumber} — briefs clean`)
}

process.exit(0)

} // end isMain guard
