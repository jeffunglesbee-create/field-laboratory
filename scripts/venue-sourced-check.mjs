// Every venue the sourcing run accepted is in the table, exactly as sourced.
//
// docs/CC-CMD-2026-10-20-outdoor-venue-sourcing.md, stage 4. The rows in
// src/Venues.fs's "sourced" block are generated from
// outbox/venue-source-results-latest.json (`--write` below), never typed. This
// asserts, with no network, that the table and the artifact still agree: a row
// deleted, a digit changed, a roof or zone edited by hand, or an accepted venue
// never added, is a failure here and not a quiet drift.
//
// And the other direction: every row in the sourced block is an accepted
// result, so a hand-added row cannot hide inside the generated block.
//
// Usage:  node scripts/venue-sourced-check.mjs --self-test
//         node scripts/venue-sourced-check.mjs
//         node scripts/venue-sourced-check.mjs --write   (regenerates the block)

import { readFileSync, writeFileSync } from 'node:fs'
import { createChecks, finish, isMain } from './checks.mjs'

const RESULTS = 'outbox/venue-source-results-latest.json'
const TABLE = 'src/Venues.fs'
export const BEGIN = '      // --- BEGIN sourced (generated by scripts/venue-sourced-check.mjs --write; do not edit by hand)'
export const END = '      // --- END sourced'

const ROOF = { open: 'OpenAir', retractable: 'Retractable', dome: 'Dome' }
const fs4 = x => x.toFixed(4)
const fsString = s => s.replace(/\\/g, '\\\\').replace(/"/g, '\\"')

/** One accepted result as the F# line the table carries. */
export const rowOf = a => `      at "${fsString(a.name)}" ${fs4(a.lat)} ${fs4(a.lon)} ${ROOF[a.roof]} "${a.zone}"`

/** The generated block: a header naming the run, then one row per accepted venue. */
export const blockOf = results => [
  BEGIN,
  `      //     From ${RESULTS}, run ${results.run ?? 'unknown'} at ${results.at}: ${results.accepted.length} of ${results.of} candidates`,
  '      //     accepted (two independent families within 0.02 degrees, an unambiguous name, a roof and a zone).',
  '      //     The rest are in its review list, deliberately not here.',
  ...[...results.accepted].sort((a, b) => a.name.localeCompare(b.name)).map(rowOf),
  END,
].join('\n')

/** The rows between BEGIN and END, parsed back. */
export const sourcedRows = text => {
  const i = text.indexOf(BEGIN), j = text.indexOf(END)
  if (i < 0 || j < i) return null
  return [...text.slice(i, j).matchAll(/^\s*at "((?:[^"\\]|\\.)*)"\s+(-?\d+\.\d+)\s+(-?\d+\.\d+)\s+(\w+)\s+"([^"]+)"/gm)]
    .map(m => ({ name: m[1].replace(/\\(.)/g, '$1'), lat: m[2], lon: m[3], roof: m[4], zone: m[5] }))
}

/** Disagreements between the accepted results and the sourced block. */
export const compare = (results, text) => {
  const rows = sourcedRows(text)
  if (!rows) return { missingBlock: true, absent: [], changed: [], extra: [] }
  const byName = new Map(rows.map(r => [r.name, r]))
  const accepted = new Map(results.accepted.map(a => [a.name, a]))
  const absent = [], changed = []
  for (const a of results.accepted) {
    const r = byName.get(a.name)
    if (!r) { absent.push(a.name); continue }
    const want = { lat: fs4(a.lat), lon: fs4(a.lon), roof: ROOF[a.roof], zone: a.zone }
    const diff = Object.keys(want).filter(k => want[k] !== r[k])
    if (diff.length) changed.push(`${a.name}: ${diff.map(k => `${k} ${r[k]} != ${want[k]}`).join(', ')}`)
  }
  const extra = rows.filter(r => !accepted.has(r.name)).map(r => r.name)
  return { missingBlock: false, absent, changed, extra, rows: rows.length }
}

/** Placements that were accepted once and were wrong. A row with this NAME near
 *  this point must never be in the table. Found by auditing a sourcing run's new
 *  rows against where the places are, which the calibration cannot see: neither is
 *  a table row with a known answer. */
export const KNOWN_BAD = [
  { name: 'GEHA Field at Arrowhead Stadium', lat: 10.9269, lon: -74.8006, why: 'Estadio Metropolitano, Barranquilla: taken from Colombia, the home team of a World Cup game' },
  { name: 'St James Park', lat: 54.9755, lon: -1.6218, why: "Newcastle's ground, accepted for Exeter's: article search and OpenStreetMap both returned the famous one" },
]
const ROW = /^\s*at "((?:[^"\\]|\\.)+)"\s+(-?\d+\.\d+)\s+(-?\d+\.\d+)/gm
/** Table rows (all of them, not only the sourced block) that sit on a known-bad placement. */
export const onKnownBad = (text, bad = KNOWN_BAD) =>
  [...text.matchAll(ROW)].flatMap(m => bad
    .filter(b => b.name === m[1].replace(/\\(.)/g, '$1') && Math.abs(b.lat - Number(m[2])) <= 0.02 && Math.abs(b.lon - Number(m[3])) <= 0.02)
    .map(b => `${b.name} at ${m[2]},${m[3]}: ${b.why}`))

const selfTest = () => {
  const { check, summarize } = createChecks()
  const res = { run: '1', at: 't', of: 2, accepted: [
    { name: 'Anfield', lat: 53.4308, lon: -2.9608, roof: 'open', zone: 'Europe/London' },
    { name: 'Joe\'s "Field"', lat: 1, lon: 2, roof: 'dome', zone: 'America/Chicago' }] }
  const good = `x\n${blockOf(res)}\ny`
  const c = compare(res, good)
  check('a generated block agrees with its results', c.absent.length + c.changed.length + c.extra.length === 0 && c.rows === 2, JSON.stringify(c))
  check('a name with quotes survives the F# string and is read back', sourcedRows(good).some(r => r.name === 'Joe\'s "Field"'))
  check('A DELETED ROW IS CAUGHT', compare(res, good.replace(/^.*Anfield.*\n/m, '')).absent.join() === 'Anfield')
  check('A CHANGED DIGIT IS CAUGHT', compare(res, good.replace('53.4308', '53.4309')).changed.length === 1)
  check('A HAND-EDITED ROOF IS CAUGHT', compare(res, good.replace('OpenAir', 'Retractable')).changed.length === 1)
  check('A HAND-ADDED ROW IN THE BLOCK IS CAUGHT',
    compare(res, good.replace(END, `      at "Made Up Park" 1.0000 1.0000 OpenAir "UTC"\n${END}`)).extra.join() === 'Made Up Park')
  check('A KNOWN-BAD PLACEMENT IS CAUGHT BY NAME AND POINT', onKnownBad('      at "St James Park" 54.9755 -1.6218 OpenAir "Europe/London"\n').length === 1)
  check('...the same point under the right name is not (St. James\' Park is Newcastle\'s)', onKnownBad('      at "St. James\' Park" 54.9755 -1.6218 OpenAir "Europe/London"\n').length === 0)
  check('...and the same name somewhere else is not (Exeter\'s own ground)', onKnownBad('      at "St James Park" 50.7305 -3.5214 OpenAir "Europe/London"\n').length === 0)
  check('a missing block is its own failure, not zero rows', compare(res, 'no block').missingBlock === true)
  finish(summarize())
}

if (isMain(import.meta.url)) {
  if (process.argv.includes('--self-test')) selfTest()
  else {
    const results = JSON.parse(readFileSync(RESULTS, 'utf8'))
    const text = readFileSync(TABLE, 'utf8')
    if (process.argv.includes('--write')) {
      const i = text.indexOf(BEGIN), j = text.indexOf(END)
      if (i < 0 || j < i) { console.error(`no ${BEGIN.trim()} … ${END.trim()} block in ${TABLE}`); process.exit(2) }
      writeFileSync(TABLE, text.slice(0, i) + blockOf(results) + text.slice(j + END.length))
      console.log(`wrote ${results.accepted.length} sourced row(s) into ${TABLE}`)
    } else {
      const { check, summarize } = createChecks()
      const c = compare(results, text)
      check('the table carries a generated sourced block', !c.missingBlock, `no BEGIN/END sourced markers in ${TABLE}`)
      check(`every accepted venue is in the table (${results.accepted.length} accepted)`, c.absent.length === 0, c.absent.slice(0, 10).join(', '))
      check('...with exactly the sourced coordinates, roof and zone', c.changed.length === 0, c.changed.slice(0, 10).join('; '))
      check('...and nothing in the sourced block that the run did not accept', c.extra.length === 0, c.extra.join(', '))
      check('no table row sits on a placement that was once accepted and wrong', onKnownBad(text).length === 0, onKnownBad(text).join('; '))
      check('there are accepted venues to check at all', results.accepted.length > 0, 'the results artifact accepted nothing')
      finish(summarize())
    }
  }
}
