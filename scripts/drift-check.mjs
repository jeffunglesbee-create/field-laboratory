// The drift sentinel.
//
// Fetches a real /context/date payload and runs THIS REPO'S OWN compiled F#
// decoders over it. Not a JavaScript reimplementation — a parallel schema would
// drift from the F# one and make the whole exercise meaningless.
//
// The question it exists to answer: the decoders are proven correct and are not
// proven necessary. Both captures in data/ decoded first try, and every failure
// result in this repo comes from a fixture corrupted on purpose. Whether FIELD's
// live payloads actually drift is unmeasured. This measures it, daily.
//
// A long green run is a real result and must be reported as one — it argues that
// the decoders are insurance nobody has claimed on. Do not tune this toward
// passing.
//
//   node scripts/drift-check.mjs --url https://…/context/date/2026-08-09
//   node scripts/drift-check.mjs --file data/games-2026-08-09.json

import { readFile } from 'node:fs/promises'
import { readFileSync, writeFileSync } from 'node:fs'
import { createChecks, toArray, NESTED } from './checks.mjs'
import { censusOf, transitions, mergeSeries, vacuousReadings, alarmLine } from './odds-coverage.mjs'
import { decodePayload, sportMeta, oddsStory, spreadOf, spreadPricingOf, totalOf, favouriteAgreement, dateKeying, fieldDayIso } from '../build/Desk.js'

const args = process.argv.slice(2)
const argOf = flag => {
  const i = args.indexOf(flag)
  return i === -1 ? null : args[i + 1]
}

const url = argOf('--url')
const file = argOf('--file')
// `--seed` exists so the committed history is GENERATED by the same censusOf
// the alarm reads, never hand-written. A hand-written seed is a copy of the
// capture; the first one written here carried `sports: {}` for both dates,
// which left the alarm unable to fire while the check still printed PASS.
const seed = args.includes('--seed')
if (!url && !file) {
  console.error('usage: drift-check.mjs (--url <url> | --file <path>) [--seed]')
  process.exit(2)
}

const source = url || file
let body
try {
  if (url) {
    const res = await fetch(url)
    if (!res.ok) throw new Error(`HTTP ${res.status}`)
    body = await res.text()
  } else {
    body = await readFile(file, 'utf8')
  }
} catch (e) {
  // A fetch failure is an infrastructure problem, not drift. Say so plainly
  // rather than letting it read as a decoder failure in the log.
  console.error(`FETCH FAILED: ${e.message}`)
  console.log(`RESULT|${source}|fetch-failed|0|0|${e.message}`)
  process.exit(1)
}

const { check, summarize } = createChecks()

// Committed, because the transition alarm compares against EARLIER PROBED
// DATES and a series held only in memory can never see a transition at all.
const SERIES_PATH = 'outbox/odds-coverage-series.json'
// ONE CLOCK READ, CAPTURED AT THE TOP. Reading the instant inline in the
// reading below cost this file's two gate rows 30 points each on
// row-confidence's determinism term, and the rule it broke is the one CI run
// 31456294086 exists to enforce: a script that reads the clock more than once
// can straddle a boundary between two of its own lines. Nothing here needs the
// instant twice.
const PROBED_AT = new Date().toISOString()
let coverage = {}
let coverageAlarms = []

const result = decodePayload(body)
const decoded = result.tag === 0
const payload = decoded ? result.fields[0] : null
const decodeError = decoded ? '' : String(result.fields[0]).replace(/\s+/g, ' ').slice(0, 300)

check('payload decodes', decoded, decodeError)

let games = []
let malformed = []
let unmodelled = []
let declaredUnmodelled = []
let vocabulary = []
let oddsShape = { withBoth: 0, notSequenced: 0, moved: 0, unmoved: 0, single: 0, none: 0 }
let lineShape = { spreads: 0, unbalanced: 0, pickem: 0, oneSided: 0, emptySpread: 0, priced: 0, unpriced: 0, halfPriced: 0, totals: 0, split: 0, oneSidedTotal: 0, emptyTotal: 0, compared: 0, mismatched: 0 }
let mismatchDetail = []
let sections = []
let deskFill = { note: 0, local_note: 0, crew: 0, tags: 0, tagsMalformed: 0 }
let keying = new Map()
let keyingExamples = []

if (decoded) {
  games = [...toArray(payload.Regular), ...toArray(payload.Postseason)]

  // ACCEPTED, not merely survived.
  //
  // `payload decodes` stopped being a real assertion the moment the game list
  // became fault-tolerant. `Decode.oneOf [ gameDecoder |> Decode.map Some;
  // Decode.succeed None ]` means a wholly broken `gameDecoder` still produces a
  // payload — one with zero games in it — and every count below then reports
  // cheerfully over an empty set.
  //
  // The mutation harness caught exactly that within one run of the change:
  // `[decoder-rejects-real]` SURVIVED, meaning `Desk.fs` was deliberately broken
  // and this script still passed. The gate row is named "decoders accept both
  // real captures", so accept has to mean all of them.
  //
  // The conservation law alone is NOT enough here and it is worth saying why:
  // a broken decoder maps every row to `None`, so `games + unnamed === rows`
  // still balances perfectly at zero games. Both captures are hand-checked to
  // contain no null-sided rows, so the assertion is the strict one.
  const rawGameRows = (() => {
    try {
      const j = JSON.parse(body)
      const n = a => (Array.isArray(a) ? a.length : 0)
      return n(j?.games?.regular) + n(j?.games?.postseason)
    } catch { return -1 }
  })()

  // THREE STATES, and `rawGameRows` already distinguished them — the value was
  // computed and then flattened into a boolean.
  //
  //   -1  the body did not parse. The `catch` above returns this precisely so
  //       an unparseable payload cannot look like a small one. Still fatal.
  //    0  the body parsed and the relay served no games. A LEGITIMATE EMPTY
  //       SLATE — a day before its first fixture. There is no conservation law
  //       to test, so testing one is not a finding.
  //   >0  rows exist: every one must decode, with nothing un-nameable.
  //
  // WHY `rawGameRows > 0` WAS THERE, in the author's own words above: "a broken
  // decoder maps every row to None, so games + unnamed === rows still balances
  // perfectly at zero games". That reasoning is right and is NOT weakened here.
  // A broken decoder against a real payload gives rawGameRows > 0 and
  // games.length === 0, which the conservation clause still fails. What the
  // clause additionally rejected was the case it was never aimed at — the relay
  // honestly serving nothing.
  //
  // The comment says "both CAPTURES are hand-checked", and that is the whole
  // story: this assertion was written for pinned fixtures, where zero rows can
  // only mean a broken decoder. drift-sentinel then pointed it at a LIVE
  // payload, where zero rows is a Monday at 03:09 ET. It went red on
  // 2026-08-31 for a relay that was answering correctly, while the run's own
  // drift-log row read `| 2026-08-31 | 0 | ok |`.
  if (rawGameRows === 0) {
    console.log('NOTE  the relay served 0 game rows and the body parsed cleanly —')
    console.log('      an empty slate. No conservation law to test on this payload.')
  } else {
    check('every game row in the capture is accepted as a game',
      rawGameRows > 0 && games.length === rawGameRows && payload.Unnamed === 0,
      `${rawGameRows} row(s) in the file, ${games.length} decoded, ${payload.Unnamed} un-nameable`)
  }

  // The three fields the relay serves as strings containing JSON. Tag 2 means
  // the outer string was present and the inner JSON did not decode — a real
  // shape change, which is exactly what this sentinel is watching for.
  for (const g of games) {
    for (const [field, value] of [['drama_arc', g.DramaArc], ['opening_odds', g.OpeningOdds], ['closing_odds', g.ClosingOdds]]) {
      if (value?.tag === NESTED.Malformed) {
        malformed.push(`${g.Id}.${field}: ${String(value.fields[0]).replace(/\s+/g, ' ').slice(0, 120)}`)
      }
    }
  }

  // The sport vocabulary the relay actually serves. This is how the Sport
  // union's registry stays evidence-driven: cases are added when a sport is
  // observed, not invented in advance, and an unmodelled one surfaces here
  // within a day rather than being quietly absorbed by a fallback.
  const byLabel = new Map()
  for (const g of games) {
    const meta = sportMeta(g.Sport)
    // `Omission` is `Some reason` when leaving a sport unmodelled is a recorded
    // decision rather than a gap. Fable compiles an F# option to the value or
    // undefined, so a truthy check is the whole test.
    const seen = byLabel.get(meta.Label) ||
      { label: meta.Label, modelled: meta.Modelled, declared: Boolean(meta.Omission), n: 0 }
    seen.n += 1
    byLabel.set(meta.Label, seen)
  }
  vocabulary = [...byLabel.values()].sort((a, b) => b.n - a.n || a.label.localeCompare(b.label))
  // Only sports that are unmodelled AND undeclared are an alarm.
  //
  // golf has been on this list since 2026-08-14 and will never leave it: the
  // relay packs a tournament and a round into home/away, so no Matchup case
  // fits, and `src/Desk.fs` records that as the correct answer. Reporting it
  // twice a day forever is an alarm that cannot be cleared, which the
  // sentinel's own issue-closing step already argues against — "an issue that
  // outlives its cause trains people to ignore the next one".
  //
  // Declared omissions still ride in the vocabulary string, marked, so they
  // stay visible without being actionable.
  unmodelled = vocabulary.filter(v => !v.modelled && !v.declared)
  declaredUnmodelled = vocabulary.filter(v => !v.modelled && v.declared)

  // The Odds Story's own shape, measured across the whole live slate rather
  // than inferred from two committed games. ODDS_STORY tags follow declaration
  // order in Desk.fs: NoPrices, SingleSnapshot, NotASequence, Unmoved, Moved.
  const ODDS_STORY = { NoPrices: 0, SingleSnapshot: 1, NotASequence: 2, Unmoved: 3, Moved: 4 }
  for (const g of games) {
    const story = oddsStory(g.OpeningOdds, g.ClosingOdds)
    switch (story.tag) {
      case ODDS_STORY.NotASequence: oddsShape.notSequenced += 1; oddsShape.withBoth += 1; break
      case ODDS_STORY.Moved:        oddsShape.moved += 1;        oddsShape.withBoth += 1; break
      case ODDS_STORY.Unmoved:      oddsShape.unmoved += 1;      oddsShape.withBoth += 1; break
      case ODDS_STORY.SingleSnapshot: oddsShape.single += 1; break
      default: oddsShape.none += 1
    }
  }

  // Line shapes across the slate. All follow declaration order in Desk.fs.
  //
  // THESE ORDINALS ARE A TRANSCRIPTION of a union declared in another language,
  // which is the copy-of-the-source shape this repo keeps finding. They were
  // re-read from `build/Desk.js` on 2026-09-21 when EmptySpread, EmptyTotal and
  // OneSidedTotal were appended — Balanced and Unbalanced are still 0 and 1,
  // because new cases go on the END. Inserting one at the top would silently
  // re-label every count this sentinel has ever written to the drift log.
  //
  // `EmptyTotal` is 2 and `OneSidedTotal` is 3, which is NOT the order they
  // read in Desk.fs's prose: EmptyTotal was appended first and OneSidedTotal
  // after it. Transcribing the comment order instead of the compiled tag table
  // would have swapped them. Read from `build/Desk.js:1269`.
  const SPREAD = { Balanced: 0, Unbalanced: 1, PickEm: 2, OneSidedSpread: 3, EmptySpread: 4 }
  const TOTAL = { OneLine: 0, TwoNumbers: 1, EmptyTotal: 2, OneSidedTotal: 3 }
  const PRICING = { BothPriced: 0, NeitherPriced: 1, OnlyOnePriced: 2 }
  const AGREE = { Agrees: 0, Disagrees: 1, NotComparable: 2 }
  for (const g of games) {
    for (const nested of [g.OpeningOdds, g.ClosingOdds]) {
      if (nested?.tag !== NESTED.Decoded) continue
      const o = nested.fields[0]
      const sp = spreadOf(o)
      if (sp != null) {
        lineShape.spreads += 1
        if (sp.tag === SPREAD.Unbalanced) lineShape.unbalanced += 1
        if (sp.tag === SPREAD.PickEm) lineShape.pickem += 1
        if (sp.tag === SPREAD.OneSidedSpread) lineShape.oneSided += 1
        if (sp.tag === SPREAD.EmptySpread) lineShape.emptySpread += 1
        // The price beside the handicap, counted only where there is one —
        // and an EMPTY spread key is not one. Without this guard the single
        // `{"home":null,"away":null}` row on 2026-08-29 lands in `unpriced`
        // alongside five rows that carry a real handicap and no price, which
        // is the same two-facts-one-number collapse `EmptySpread` was added to
        // end, reappearing one field over. `emptySpread` is its own count.
        if (sp.tag !== SPREAD.EmptySpread) {
          const pr = spreadPricingOf(o)
          if (pr.tag === PRICING.BothPriced) lineShape.priced += 1
          if (pr.tag === PRICING.NeitherPriced) lineShape.unpriced += 1
          if (pr.tag === PRICING.OnlyOnePriced) lineShape.halfPriced += 1
        }
      }
      const tl = totalOf(o)
      if (tl != null) {
        lineShape.totals += 1
        if (tl.tag === TOTAL.TwoNumbers) lineShape.split += 1
        if (tl.tag === TOTAL.OneSidedTotal) lineShape.oneSidedTotal += 1
        if (tl.tag === TOTAL.EmptyTotal) lineShape.emptyTotal += 1
      }
      const ag = favouriteAgreement(o)
      if (ag.tag !== AGREE.NotComparable) {
        lineShape.compared += 1
        if (ag.tag === AGREE.Disagrees) {
          lineShape.mismatched += 1
          // Name the game and show the numbers. A count alone is not
          // actionable, and this invariant is new enough that a mismatch is at
          // least as likely to be wrong about soccer as the data is to be wrong.
          mismatchDetail.push(
            `${sportMeta(g.Sport).Label} ${g.Id}: ML ${o.MoneylineHome}/${o.MoneylineAway} H ${o.SpreadHome}/${o.SpreadAway}`)
        }
      }
    }
  }

  // Both are real data-integrity invariants, so both fail rather than merely
  // report. A handicap whose two numbers are not opposites is not one line, and
  // a moneyline that disagrees with the handicap about who is favoured means one
  // of the two fields describes a different market.
  check('every spread is a balanced handicap', lineShape.unbalanced === 0,
    `${lineShape.unbalanced} of ${lineShape.spreads} spreads have home != -away`)
  check('moneyline and handicap agree on the favourite', lineShape.mismatched === 0,
    `${lineShape.mismatched} of ${lineShape.compared} comparable: ${[...new Set(mismatchDetail)].slice(0, 6).join(' | ')}`)
  // Not a data-integrity violation like the two above — a split total could
  // just as easily mean the relay started serving real over/under PRICES
  // instead of the line duplicated, which would be an upstream improvement.
  // It fails anyway, for the same reason an unmodelled sport does: an
  // assumption this repo encoded (`total` is one line) has stopped holding, and
  // the model needs revisiting. The alarm says investigate, not broken.
  check('every total is a single line, not two numbers', lineShape.split === 0,
    `${lineShape.split} of ${lineShape.totals} totals carry over != under — the field may now be real prices`)

  // Fill rates for the four editorial columns. All four are null in every game
  // of every capture; whether that holds on the live slate is the question.
  for (const g of games) {
    if (g.Note != null) deskFill.note += 1
    if (g.LocalNote != null) deskFill.local_note += 1
    if (g.Crew != null) deskFill.crew += 1
    if (g.Tags?.tag === NESTED.Decoded) deskFill.tags += 1
    if (g.Tags?.tag === NESTED.Malformed) deskFill.tagsMalformed += 1
  }
  // tags is the fourth double-encoded field, so it gets the same treatment as
  // the other three: a broken inner payload is a failure, not a note.
  // Which day is a game's `date`? KEYING tags follow declaration order in
  // Desk.fs: NoStartTime, SameUtcDay, StartsAfterDateUtc, StartsBeforeDateUtc.
  //
  // Not an assertion — a measurement. The laboratory keys off UTC and FIELD
  // keys off ET, and before changing anything the question is what the relay's
  // `date` column actually IS. A relay serving AFL, MLS and MLB may well key
  // each competition to its own local day, in which case ET is as wrong as UTC.
  const KEYING = ['no-start-time', 'same-utc-day', 'starts-after-date', 'starts-before-date']
  for (const g of games) {
    const k = KEYING[dateKeying(g).tag] ?? '?'
    const label = sportMeta(g.Sport).Label
    const key = `${label}:${k}`
    keying.set(key, (keying.get(key) || 0) + 1)
    // Name the games that disagree, with their numbers. A count cannot be
    // judged — that lesson cost a whole round trip on the favourite invariant.
    if (k === 'starts-after-date' || k === 'starts-before-date') {
      // g.Day is a lifted FieldDay, not a bare string — read it through the
      // accessor rather than a property that no longer exists.
      keyingExamples.push(`${label} ${g.Id}: date=${g.Day ? fieldDayIso(g.Day) : 'unreadable'} start=${g.RawStartTime}`)
    }
  }

  check('no malformed tags payloads', deskFill.tagsMalformed === 0,
    `${deskFill.tagsMalformed} of ${games.length} games have unparseable tags`)

  check('no malformed nested payloads', malformed.length === 0, malformed.join(' | '))

  // Context Graph sections. SECTION tags follow declaration order in Desk.fs:
  // Absent, EmptyOrFailed, Present.
  const SECTION = { Absent: 0, EmptyOrFailed: 1, Present: 2 }
  const sectionName = t => ['absent', 'empty-or-failed', 'present'][t] ?? '?'
  sections = ['Briefs', 'Series', 'Standings'].map(name => {
    const v = payload[name]
    const n = v?.tag === SECTION.Present ? v.fields[0].length ?? toArray(v.fields[0]).length : 0
    return { name: name.toLowerCase(), state: sectionName(v?.tag), n }
  })

  // NOT a failure. The relay collapses a rejected D1 query to [] via
  // Promise.allSettled, so `empty-or-failed` is genuinely ambiguous and firing
  // on it would alarm on every quiet slate. Recorded and tracked instead —
  // whether these sections are ever populated is a question only the log can
  // answer, which is the same standing as the drift question itself.
  check('context sections decoded', sections.length === 3,
    sections.map(s => `${s.name}=${s.state}`).join(' '))
  // Deliberately a failure, not a note. An unmodelled sport means the registry
  // is incomplete and its fixtures are rendering under an unknown convention —
  // the same class of defect as a malformed payload, and it stays loud until
  // someone adds the case.
  check('every observed sport is in the registry, or declared absent on purpose',
    unmodelled.length === 0,
    unmodelled.map(v => `${v.label} (${v.n})`).join(', '))

  // Non-vacuity, and a guard against the escape this just opened. If EVERY
  // observed sport were declared, the check above would pass while the desk
  // rendered nothing under a real convention — "all of it is fine on purpose"
  // is exactly how an exemption mechanism rots into a suppression list.
  check('the declared omissions are not the whole slate',
    vocabulary.length === 0 || declaredUnmodelled.length < vocabulary.length,
    `${declaredUnmodelled.length} of ${vocabulary.length} observed sport(s) are declared unmodelled`)
  // ── per-sport odds coverage, and the transition alarm ────────────────────
  //
  // The counters above are all counts of games that HAVE odds, so the whole
  // family is blind to a sport that stops getting any: a smaller denominator
  // reports healthy shapes. MLS went from two-way prices to 0 of 17 rows and
  // nothing here noticed.
  //
  // The series is committed, so the comparison is against real earlier probes
  // rather than against whatever happens to be in memory.
  coverage = censusOf(games, g => sportMeta(g.Sport).Label)
  const today = { date: payload?.Date ?? '(undecoded)', source, at: PROBED_AT, sports: coverage }
  let series = []
  try { series = JSON.parse(readFileSync(SERIES_PATH, 'utf8')) } catch (_) { series = [] }
  coverageAlarms = transitions(series, today)
  // ONLY A LIVE PROBE WRITES. A `--file` replay is a real payload but not a new
  // observation, and letting one append would let anybody re-date the history
  // the alarm reads — including by replaying a capture whose sports differ from
  // today's. The two committed captures were seeded deliberately, once, and are
  // marked `seed` in the file, and were written by `--file … --seed`.
  //
  // AND AN EMPTY PROBE WRITES NOTHING — `mergeSeries` refuses it. Said out loud
  // here, because a run that silently records nothing and a run that records a
  // reading look identical in the log otherwise, and the 06:37 UTC run on
  // 2026-09-21 spent a probe on a slate the relay had not built yet.
  if (url || seed) {
    if (Object.keys(coverage).length === 0)
      console.log(`coverage: NOT RECORDED — the probe saw no sport on ${today.date}; unread, not zero`)
    try { writeFileSync(SERIES_PATH, JSON.stringify(mergeSeries(series, { ...today, seed: seed || undefined }), null, 2) + '\n') } catch (_) {}
  }

  // A FAILURE, not a note. A sport that carried odds and now carries none on
  // rows that exist is a regression with a direction, and it is the one thing
  // this census was added to catch. A sport that has NEVER carried odds is not
  // alarmed on — that is a coverage decision, and a red nobody can clear is a
  // red everybody learns to skip.
  // THE ALARM'S DENOMINATOR, checked separately from the alarm.
  // A committed reading with no sports cannot produce a transition, so a
  // history made entirely of those prints PASS on the line below while being
  // incapable of failing. The first seed file written here was exactly that.
  const vacuous = vacuousReadings(series)
  check('the committed coverage history is not vacuous',
    vacuous.length === 0,
    vacuous.length ? `readings carrying no sports: ${vacuous.join(', ')} — regenerate with --file <capture> --seed` : '')

  // FATAL ON THE TRANSITION ONLY. A collapse that persists is the same event
  // on its second day, and failing this step every run would fail the whole
  // sentinel job every run — the shape that cost `verify` seven runs and 43
  // unexamined checks behind one red on 2026-09-20. The continuing ones are
  // printed above and carried in the drift log's `cov=` field, so the condition
  // stays visible as data while the alarm stays a transition.
  const newCollapses = coverageAlarms.filter(a => a.state === 'new')
  check('no sport newly lost the odds coverage it had',
    newCollapses.length === 0,
    newCollapses.map(alarmLine).join(' | '))

  check('every game has an id and both teams',
    games.every(g => g.Id && g.Home && g.Away),
    'a game decoded without id/home/away')
}

