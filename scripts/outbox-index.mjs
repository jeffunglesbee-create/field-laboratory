// Which commit wrote which outbox entry — derived from git, never typed.
//
// A Claude chat session reviewing this repo through the GitHub file API tried
// to check a claim of the form "commit X is documented by section Y" and could
// not, for a reason worth recording verbatim:
//
//   "none of the three commit hashes appear anywhere in the document's text ...
//    I don't have real git-log access through my own tools — they read file
//    contents via GitHub's API, not commit history"
//
// Two failures, and the outbox convention caused both.
//
//   1. ONE APPEND-ONLY DOCUMENT PER SESSION. A 1,289-line file accumulating
//      sections all day cannot say which commit wrote which part, so the
//      mapping lived only in chat. Retired: one document per piece of work.
//
//   2. THE DIFF THAT MISSED 400 LINES. Their staleness check compared
//      FILENAMES, and the filename never changed while the file grew by a
//      third. Their own words: "a file can grow substantially without ever
//      showing up in a filename-based comparison." One document per piece of
//      work makes new work a new filename, which is what a filename comparison
//      can actually see.
//
// This file closes the remaining gap: a reader with no `git log` still needs
// the mapping. So it is generated INTO the repo, as text, from git history —
// derived on every run, never hand-maintained, so it cannot drift into a claim
// nobody checks.
//
// Usage:  node scripts/outbox-index.mjs            (write outbox/INDEX.md)
//         node scripts/outbox-index.mjs --check    (fail if it would change)

import { execSync } from 'node:child_process'
import { readFileSync, writeFileSync, existsSync } from 'node:fs'

const INDEX = 'outbox/INDEX.md'

const render = () => {
  // %x00 delimiters, parsed positionally: a commit subject can contain
  // anything, and a pattern matching subject text desynchronises the walk.
  const raw = execSync(
    "git log --no-merges --format='%x00%H%x00%ad%x00%s' --date=short --name-only -- outbox/",
    { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 })

  const parts = raw.split('\0')
  const entries = []
  for (let i = 1; i + 2 < parts.length + 2; i += 3) {
    const sha = (parts[i] ?? '').trim()
    if (!sha) continue
    const date = (parts[i + 1] ?? '').trim()
    const body = (parts[i + 2] ?? '').split('\n')
    const files = body.slice(1).map(l => l.trim())
      .filter(f => f.startsWith('outbox/') && f !== INDEX)
    if (files.length === 0) continue
    entries.push({ sha, date, subject: body[0], files })
  }

  const lines = [
    '# Outbox index',
    '',
    '**Generated by `scripts/outbox-index.mjs` — do not edit.** Every row is read',
    'out of git history, so this file cannot claim a pairing that git does not have.',
    '',
    'It exists because a reviewer reading this repository through a file API has no',
    '`git log`, and the outbox previously offered no way to tell which commit wrote',
    'which passage. One document per piece of work, plus this mapping, is the answer.',
    '',
    'Newest first. `INDEX.md` itself is excluded — it is written after the commit it',
    'would describe, so listing itself would always be one commit stale.',
    '',
    '| commit | date | entry | commit subject |',
    '| --- | --- | --- | --- |',
  ]
  for (const e of entries) {
    for (const f of e.files) {
      const name = f.replace(/^outbox\//, '')
      // Pipes would break the table; subjects here are plain, but a future one
      // need not be.
      const subject = e.subject.replace(/\|/g, '\\|')
      lines.push(`| \`${e.sha.slice(0, 7)}\` | ${e.date} | [${name}](${name}) | ${subject} |`)
    }
  }
  lines.push('')
  return lines.join('\n')
}

const next = render()

if (process.argv.includes('--check')) {
  const current = existsSync(INDEX) ? readFileSync(INDEX, 'utf8') : ''
  if (current === next) {
    console.log(`${INDEX} is current.`)
    process.exit(0)
  }
  // Not a hard failure by default: the index is written by the status workflow
  // AFTER the commit it describes, so being one commit behind is its normal
  // resting state, not a defect. Callers that want strictness pass --strict.
  console.log(`${INDEX} would change.`)
  process.exit(process.argv.includes('--strict') ? 1 : 0)
}

writeFileSync(INDEX, next)
const rows = next.split('\n').filter(l => l.startsWith('| `')).length
console.log(`${INDEX}: ${rows} entry/commit pairings`)
